import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { stripTypeScriptTypes } from "node:module"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const entries = [
  ["src/backend.ts", "dist/backend.js"],
  ["src/frontend.ts", "dist/frontend.js"],
]

for (const [sourcePath, outputPath] of entries) {
  const source = await readFile(resolve(root, sourcePath), "utf8")
  const output = stripTypeScriptTypes(source, {
    mode: "transform",
    sourceMap: false,
  })
  await mkdir(dirname(resolve(root, outputPath)), { recursive: true })
  await writeFile(
    resolve(root, outputPath),
    `// Generated from ${sourcePath}. Do not edit this file directly.\n${output}`,
    "utf8",
  )
  console.log(`${sourcePath} -> ${outputPath}`)
}
