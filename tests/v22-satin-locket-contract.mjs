import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const css = await readFile(new URL('../src/studio/styles.ts', import.meta.url), 'utf8')
const mini = await readFile(new URL('../src/miniplayer/controller.ts', import.meta.url), 'utf8')
const compiled = await readFile(new URL('../dist/frontend.js', import.meta.url), 'utf8')
assert.match(css, /Satin Locket: use the same restrained fill\/accent language/)
assert.match(css, /data-collapsed='true'[^\n]*border:2px solid color-mix/)
assert.match(css, /data-collapsed='true'[^\n]*box-shadow:inset 0 1px 0/)
assert.doesNotMatch(css, /border:4px solid #45344d/)
assert.doesNotMatch(css, /linear-gradient\(140deg,#f0d0da/)
assert.match(css, /data-collapsed='true'\]\[data-state='running'\]::before/)
assert.match(css, /background:conic-gradient\(var\(--lumiverse-accent/)
assert.match(css, /data-indeterminate='true'\]::before/)
assert.match(css, /prefers-reduced-motion:reduce/)
assert.match(css, /\.ss-miniplayer\[data-collapsed='true'\] \.ss-mini-satellite \{ display:grid; \}/)
assert.match(mini, /mini\.style\.setProperty\("--ss-mini-progress"/)
assert.match(mini, /mini\.dataset\.indeterminate = String/)
assert.ok(compiled.includes('Satin Locket: use the same restrained fill/accent language'))
console.log('v22 satin Locket CSS, progress state, badge and compiled frontend: PASS')
