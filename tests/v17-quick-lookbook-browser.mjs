  assert.ok(navBox&&dialog&&navBox.width<=width+1,`Lookbook rail fits ${width}px`)
  assert.ok(dialog.x>=-1&&dialog.x+dialog.width<=width+1,`Lookbook dialog fits ${width}px`)
  const metrics=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,viewport:innerWidth,nav:document.querySelector('.ss-lookbook-rail')?.scrollWidth}))
