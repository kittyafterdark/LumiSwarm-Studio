import { chromium } from 'playwright'
import { readFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { existsSync } from 'node:fs'
import assert from 'node:assert/strict'
const exe=process.env.STUDIO_CHROMIUM_PATH || (existsSync(chromium.executablePath())?chromium.executablePath():'/usr/bin/chromium')
const browser=await chromium.launch({executablePath:exe,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']})
const markup=await readFile(resolve('tests/ui-harness.html'),'utf8')
const bundled=await readFile(resolve('dist/frontend.js'),'utf8')
const fixture=markup.replace('import { setup } from "../dist/frontend.js"',bundled.replaceAll('</script','<\\/script'))
const shots=resolve('docs/screenshots'); await mkdir(shots,{recursive:true})
const errors=[]
async function mount(width,height,mobile=false){
 const page=await browser.newPage({viewport:{width,height},isMobile:mobile,hasTouch:mobile})
 page.on('pageerror',e=>errors.push(`${width}: ${e.message}`))
 await page.setContent(fixture); await page.locator('.ss-shell').waitFor(); await page.locator('[data-action="close-studio"]').first().click()
 return page
}
try {
 const page=await mount(1440,900)
 const mini=page.locator('[data-role="miniplayer"]'); const menu=page.locator('[data-role="mini-context-menu"]'); const stripMenu=page.locator('[data-role="mini-strip-menu"]')
 assert.equal(await mini.getAttribute('data-collapsed'),'true')
 assert.equal(await page.locator('.ss-mini-satellite').isVisible(),true)
 // Right click the locket itself, including its border: the native browser menu must not win.
 await mini.click({button:'right',position:{x:16,y:14}})
 assert.equal(await menu.isVisible(),true,'right click must open context menu')
 assert.equal(await menu.locator('button').count(),4)
 const computed=await menu.evaluate(el=>({parent:el.parentElement?.tagName,position:getComputedStyle(el).position,z:getComputedStyle(el).zIndex,dimensions:el.getBoundingClientRect().toJSON()}))
 const orbRect=await mini.boundingBox()
 assert.ok(computed.dimensions.y>orbRect.y-220,'Right-click menu must anchor to the orb, not teleport to the page header')
 assert.equal(computed.parent,'HTML')
 assert.equal(computed.position,'fixed')
 assert.ok(Number(computed.z)>100000)
 await page.screenshot({path:resolve(shots,'v18-right-click-menu.png')})
 await menu.locator('[data-action="mini-menu-toggle"]').click()
 assert.equal(await mini.getAttribute('data-quick-view'),'rail')
 await page.locator('[data-action="mini-show-menu"]').first().click()
 assert.equal(await stripMenu.isVisible(),true,'⋯ in rail must open dedicated toolkit menu')
 await page.keyboard.press('Escape'); assert.equal(await stripMenu.isVisible(),false)
 await page.screenshot({path:resolve(shots,'v18-action-rail.png')})
 await page.locator('[data-action="mini-compose"]').click()
 assert.equal(await mini.getAttribute('data-quick-view'),'composer')
 assert.equal(await page.locator('.ss-mini-artwork').isVisible(),true)
 await page.locator('[data-role="mini-prompt"]').fill('composed prompt preserved')
 await page.locator('[data-role="mini-negative"]').fill('no blur')
 await page.locator('[data-action="mini-toggle-negative"]').click()
 assert.equal(await mini.getAttribute('data-negative-open'),'false')
 assert.equal(await page.locator('.ss-mini-negative-field').isVisible(),false)
 await page.locator('[data-action="mini-toggle-negative"]').click()
 assert.equal(await page.locator('[data-role="mini-negative"]').inputValue(),'no blur')
 await page.locator('[data-action="mini-settings"]').click()
 assert.equal(await page.locator('[data-role="mini-settings-screen"]').isVisible(),true,'composer settings replace the old ⋯')
 await page.screenshot({path:resolve(shots,'v18-composer-menu.png')})
 await page.locator('[data-action="mini-settings"]').click()
 await page.locator('[data-action="mini-show-menu"]').click()
 assert.equal(await stripMenu.isVisible(),true)
 await stripMenu.locator('[data-action="mini-strip-collapse"]').click()
 assert.equal(await mini.getAttribute('data-collapsed'),'true')
 await page.locator('.ss-mini-preview').click()
 await page.locator('[data-action="mini-compose"]').click()
 assert.equal(await page.locator('[data-role="mini-prompt"]').inputValue(),'composed prompt preserved')
 await page.screenshot({path:resolve(shots,'v18-composer-desktop.png')})
 await page.close()
 for(const width of [320,360,390]){
  const mobile=await mount(width,720,true)
  const panel=mobile.locator('[data-role="miniplayer"]'); const m=mobile.locator('[data-role="mini-context-menu"]'); const sm=mobile.locator('[data-role="mini-strip-menu"]')
  // Mobile opt-in is required for expansion but context menu must work regardless.
  await panel.click({button:'right'})
  assert.equal(await m.isVisible(),true,`${width}px context menu on collapsed orb`)
  let r=await m.boundingBox(); assert.ok(r.x>=0&&r.x+r.width<=width+1,`${width}px menu in viewport`)
  await mobile.keyboard.press('Escape')
  await mobile.locator('.ss-mini-preview').click()
  assert.equal(await mobile.locator('.ss-shell').isVisible(),true,'Opt-out orb opens Studio')
  await mobile.locator('[data-role="mobile-quick-create"]').evaluate(el=>{el.checked=true;el.dispatchEvent(new Event('change',{bubbles:true}))})
  await mobile.locator('[data-action="close-studio"]').first().click()
  await mobile.locator('.ss-mini-preview').click()
  assert.equal(await panel.getAttribute('data-quick-view'),'rail')
  await mobile.locator('[data-action="mini-show-menu"]').first().click()
  assert.equal(await sm.isVisible(),true,`⋯ must open toolkit menu at ${width}px`)
  r=await sm.boundingBox(); assert.ok(r.x>=0&&r.x+r.width<=width+1,`⋯ menu in viewport at ${width}px`)
  await mobile.keyboard.press('Escape')
  await mobile.locator('[data-action="mini-compose"]').click()
  const panelRect=await panel.boundingBox(); assert.ok(panelRect.x>=-1&&panelRect.x+panelRect.width<=width+1,`Composer ${width}px bounds`)
  await mobile.locator('[data-action="mini-settings"]').click(); assert.equal(await mobile.locator('[data-role="mini-settings-screen"]').isVisible(),true)
  await mobile.keyboard.press('Escape')
  if(width===360) await mobile.screenshot({path:resolve(shots,'v18-composer-mobile.png')})
  await mobile.close()
 }
 // Host body zoom should not displace the menu away from the launcher.
 for (const scale of [0.5,0.75,1.25,1.5]) {
  const zoomPage=await browser.newPage({viewport:{width:1280,height:800}})
  zoomPage.on('pageerror',e=>errors.push(`zoom ${scale}: ${e.message}`))
  await zoomPage.setContent(fixture)
  await zoomPage.locator('.ss-shell').waitFor()
  await zoomPage.evaluate(z=>{document.body.style.zoom=String(z)},scale)
  await zoomPage.locator('[data-action="close-studio"]').first().evaluate(node=>node.click())
  await zoomPage.locator('.ss-miniplayer').click({button:'right'})
  const locket=await zoomPage.locator('.ss-miniplayer').boundingBox()
  const menuBox=await zoomPage.locator('[data-role="mini-context-menu"]').boundingBox()
  assert.ok(menuBox?.x>=0&&menuBox.x+menuBox.width<=1280&&menuBox.y>=0&&menuBox.y+menuBox.height<=800,`${scale} body zoom keeps menu in viewport`)
  assert.ok(menuBox.y>locket.y-220,`${scale} body zoom keeps menu adjacent to orb`)
  await zoomPage.close()
 }
 // Both navigation actions must reach the actual Studio surfaces, not merely hide their menu.
 const navPage=await mount(1440,900)
 await navPage.locator('.ss-miniplayer').click({button:'right'})
 await navPage.locator('[data-action="mini-menu-studio"]').click()
 assert.equal(await navPage.locator('.ss-shell').isVisible(),true,'Open Studio action works')
 await navPage.locator('[data-action="close-studio"]').first().click()
 await navPage.locator('.ss-miniplayer').click({button:'right'})
 await navPage.locator('[data-action="mini-menu-library"]').click()
 assert.equal(await navPage.locator('.ss-shell').isVisible(),true,'Open Library enters Studio')
 assert.equal(await navPage.locator('[data-role="output-library"]').isVisible().catch(()=>false),true,'Open Library opens its actual view')
 await navPage.close()
 const longPage=await mount(390,844,true)
 await longPage.locator('.ss-miniplayer').evaluate(node=>{
  const r=node.getBoundingClientRect()
  node.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,buttons:1,pointerType:'touch',pointerId:77,clientX:r.left+r.width/2,clientY:r.top+r.height/2}))
 })
 await longPage.waitForTimeout(620)
 assert.equal(await longPage.locator('.ss-mini-context-menu').isVisible(),true,'Touch long-press opens the context menu')
 await longPage.evaluate(()=>window.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerType:'touch',pointerId:77})))
 await longPage.close()
 assert.deepEqual(errors,[])
 console.log('v18 locket/right-click/⋯/menu actions, composer, body zoom and narrow screens: PASS')
} finally { await browser.close() }
